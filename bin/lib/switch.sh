# shellcheck shell=sh
# oc switch local|cloud — flip Claude Code between local Ollama and cloud Anthropic.
# Implementation: rewrites ~/.config/ollama-claude/claude-code.env to either
# export the local base URL + ollama token, or to unset everything so Claude
# Code falls through to its default cloud endpoint with the user's real key.

# shellcheck source=../../lib/log.sh
. "$OC_LIB_DIR/log.sh"
# shellcheck source=../../lib/config.sh
. "$OC_LIB_DIR/config.sh"
# shellcheck source=../../lib/claude.sh
. "$OC_LIB_DIR/claude.sh"
# shellcheck source=../../lib/hooks.sh
. "$OC_LIB_DIR/hooks.sh"

_switch_usage() {
  cat << 'EOF'
USAGE
  oc switch local        # Claude Code talks to local Ollama
  oc switch cloud        # Claude Code talks to Anthropic
  oc switch              # show current mode

The active profile may forbid the cloud direction (e.g. security-research).
EOF
}

oc_cmd_switch() {
  if [ $# -eq 0 ]; then
    printf 'env file says:  %s\n' "$(oc_claude_file_state)"
    printf 'current shell:  %s\n' "$(oc_claude_switch_state)"
    if [ "$(oc_claude_file_state)" != "$(oc_claude_switch_state)" ]; then
      printf '\nThe file and your shell disagree. Source the env file to apply:\n'
      printf '  source %s/claude-code.env\n' "$(oc_config_home)"
    fi
    return 0
  fi

  mode="$1"
  case "$mode" in
    local | cloud) ;;
    -h | --help)
      _switch_usage
      return 0
      ;;
    *)
      oc_log error "invalid switch: $mode"
      _switch_usage >&2
      return 2
      ;;
  esac

  # Respect profile forbid_cloud
  profile_file="$(oc_config_home)/profile"
  if [ "$mode" = "cloud" ] && [ -r "$profile_file" ]; then
    profile=$(cat "$profile_file" 2> /dev/null || echo default)
    case "$profile" in
      security-research)
        oc_die "profile '$profile' forbids cloud mode. Fork the profile if you intend to switch."
        ;;
    esac
  fi

  from=$(oc_claude_switch_state)
  OC_SWITCH_FROM="$from" OC_SWITCH_TO="$mode" oc_run_hook pre-switch
  [ "$mode" = "cloud" ] && OC_SWITCH_FROM="$from" oc_run_hook pre-cloud

  env_file="$(oc_config_home)/claude-code.env"
  mkdir -p "$(dirname "$env_file")"

  case "$mode" in
    local)
      oc_render_claude_env "http://127.0.0.1:11434" "$env_file" > /dev/null
      oc_log ok "switched to local; source $env_file in your shell (or restart Claude Code if already wired)"
      ;;
    cloud)
      cat > "$env_file" << 'EOF'
# Generated by ollama-claude. Switched to cloud mode.
# Claude Code will use its default endpoint and your existing ANTHROPIC_API_KEY.
unset ANTHROPIC_BASE_URL
unset ANTHROPIC_AUTH_TOKEN
EOF
      chmod 0600 "$env_file"
      oc_log ok "switched to cloud; restart Claude Code or re-source $env_file"
      ;;
  esac

  OC_SWITCH_TO="$mode" oc_run_hook post-switch
}
