# oc init — 3-question wizard that writes a `.ollama-claude.toml` to cwd.

# shellcheck source=../../lib/log.sh
. "$OC_LIB_DIR/log.sh"
# shellcheck source=../../lib/ui.sh
. "$OC_LIB_DIR/ui.sh"
# shellcheck source=../../lib/detect.sh
. "$OC_LIB_DIR/detect.sh"

_init_usage() {
  cat << 'EOF'
USAGE
  oc init [--profile NAME] [--topology MODE] [--wire-up yes|no]

Writes .ollama-claude.toml to the current directory. Existing file is
preserved unless --force is passed.
EOF
}

oc_cmd_init() {
  profile="${OC_PROFILE:-}"
  topology="${OC_TOPOLOGY:-}"
  wire="${OC_WIRE_UP:-}"
  force=0
  while [ $# -gt 0 ]; do
    case "$1" in
      --profile)
        profile="$2"
        shift 2
        ;;
      --topology)
        topology="$2"
        shift 2
        ;;
      --wire-up)
        wire="$2"
        shift 2
        ;;
      --force)
        force=1
        shift
        ;;
      -h | --help)
        _init_usage
        return 0
        ;;
      *)
        oc_log error "unknown flag: $1"
        _init_usage >&2
        return 2
        ;;
    esac
  done

  out=".ollama-claude.toml"
  if [ -e "$out" ] && [ "$force" != "1" ]; then
    oc_log warn "$out already exists; pass --force to overwrite"
    return 1
  fi

  oc_detect

  if [ -z "$topology" ]; then
    topology=$(oc_select "Topology" "same" "same" "split-host" "split-client")
  fi
  if [ -z "$profile" ]; then
    profile=$(oc_select "Profile" "default" "default" "security-research" "data-science" "web-dev" "minimalist" "team")
  fi
  if [ -z "$wire" ]; then
    if oc_confirm "Wire up Claude Code now?" yes; then wire="yes"; else wire="no"; fi
  fi

  cat > "$out" << EOF
# \$schema: https://ollama-claude.dev/schema/config-v1.json
# Generated by oc init.

[active]
profile = "$profile"

[topology]
default = "$topology"

# Pin models by digest for reproducibility. Run \`oc models pin\` once
# the models are installed to fill these in.
# [[models]]
# name     = "qwen3:8b"
# provider = "ollama"
# roles    = ["fast", "tools"]
# digest   = "sha256:..."
EOF

  oc_log ok "wrote $out"
  case "$wire" in yes) oc_log info "next: oc wire-up" ;; esac
}
