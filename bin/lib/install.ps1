function Invoke-OcInstall {
    [CmdletBinding()]
    param(
        [string]$Topology = $env:OC_TOPOLOGY,
        [string]$AllowFrom = $env:OC_ALLOW_FROM,
        [string]$RemoteHost = $env:OC_HOST,
        [string]$Profile = 'default'
    )

    Write-Host ('==> Detecting hardware')
    $d = Get-OcDetection
    $d | Show-OcDetectionReport

    if (-not $Topology) {
        if ([Environment]::UserInteractive -and ([Console]::IsInputRedirected -eq $false)) {
            $choice = Read-Host 'Topology (same / split-host / split-client) [same]'
            $Topology = if ($choice) { $choice } else { 'same' }
        } else {
            $Topology = 'same'
            Write-Host '[info] no topology specified, defaulting to same (non-interactive)'
        }
    }

    Write-Host ('==> Topology: {0}' -f $Topology)
    Write-Host ('==> Profile:  {0}' -f $Profile)

    if ($Topology -eq 'split-host' -and -not $AllowFrom) {
        throw "split-host requires -AllowFrom CIDR (or OC_ALLOW_FROM env var)"
    }
    if ($Topology -eq 'split-client' -and -not $RemoteHost) {
        throw "split-client requires -RemoteHost HOST:PORT (or OC_HOST env var)"
    }

    if ($Topology -ne 'split-client') {
        if (-not (Get-Command ollama -ErrorAction SilentlyContinue)) {
            Write-Host '[info] installing Ollama via winget'
            winget install --silent --accept-source-agreements --accept-package-agreements Ollama.Ollama
        } else {
            Write-Host '[ ok ] Ollama already installed'
        }
    }

    # Persist topology/profile
    $cfg = Join-Path $env:USERPROFILE '.config\ollama-claude'
    New-Item -ItemType Directory -Path $cfg -Force | Out-Null
    Set-Content -Path (Join-Path $cfg 'topology') -Value $Topology
    Set-Content -Path (Join-Path $cfg 'profile')  -Value $Profile

    # Write the PowerShell env file
    $baseUrl = switch ($Topology) {
        'split-client' { "http://$RemoteHost" }
        default        { 'http://127.0.0.1:11434' }
    }
    $envFile = Join-Path $cfg 'claude-code.ps1'
    @"
# Generated by ollama-claude. Dot-source to wire Claude Code:
#   . $envFile
`$env:ANTHROPIC_BASE_URL = '$baseUrl'
`$env:ANTHROPIC_AUTH_TOKEN = 'ollama'
Remove-Item Env:ANTHROPIC_API_KEY -ErrorAction SilentlyContinue
"@ | Set-Content -Path $envFile -Encoding UTF8
    Write-Host ('[ ok ] wrote {0}' -f $envFile)

    Write-Host "`n==> Setup complete"
    Write-Host ''
    Write-Host 'Next steps:'
    Write-Host "  . $envFile"
    Write-Host '  claude     # Claude Code now talks to local Ollama'
}
